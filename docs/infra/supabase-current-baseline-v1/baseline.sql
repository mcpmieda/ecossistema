  SELECT sum(1 << p.position)::integer FROM (VALUES(0,'am1',1),(1,'am2',2),(2,'am3',3),
    (3,'rec1',1),(4,'rec2',2),(5,'rec3',3)) p(position,field,term)
  WHERE EXISTS (SELECT 1 FROM jsonb_array_elements(raw.payload_json->'offers') o
