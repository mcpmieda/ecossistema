"""Static proof that two selectors never match one element: the classes of their last compound
never appear together in any source file (so no className can carry both), and each class is ours
(written in some .tsx/.ts file), not a library's."""
import functools
import json
import os
import re
import subprocess
import sys

ROOT = os.path.realpath(os.getcwd())


def inside_root(path):
    """Only files inside the repository (run from its root) are read or written."""
    full = os.path.realpath(path)
    if os.path.commonpath([full, ROOT]) != ROOT:
        sys.exit(f'outside the repository: {path}')
    return full


# Usage: python scripts/sonar/css-static-disjoint.py <file.css>... <measured.json> <out.json>
css_files = [inside_root(f) for f in sys.argv[1:-2]]
measured_path, out_path = inside_root(sys.argv[-2]), inside_root(sys.argv[-1])
with open(measured_path, encoding='utf8') as handle:
    measured = json.load(handle)
pairs = set()
for f in css_files:
    out = subprocess.run([sys.executable, 'scripts/sonar/css-merge-duplicates.py', f, '--disjoint', measured_path],
                         capture_output=True, text=True, encoding='utf8').stdout
    for line in out.splitlines():
        if line.startswith('ATENCAO '):
            a, rest = line[8:].split('  <->  ', 1)
            b = rest.rsplit(': [', 1)[0]
            pairs.add((a, b))

src = subprocess.run(['git', 'ls-files', 'src', 'tests', '*.html'], capture_output=True, text=True).stdout.split()
src = [p for p in src if p.endswith(('.tsx', '.ts', '.html'))]
texts = {}
for path in src:
    with open(path, encoding='utf8') as handle:
        texts[path] = handle.read()


# Every string literal (quotes and template literals): a className is one of them, or is built
# from several kept in one expression; a ternary between two literals is also caught by the
# expression scan below.
literals = []
for t in texts.values():
    literals += re.findall(r"'[^'\n]*'|\"[^\"\n]*\"|`[^`]*`", t)
    literals += re.findall(r'className=\{[^}]*\}', t)


def last_classes(sel):
    if ',' in sel:
        return None
    last = re.split(r'\s*[\s>+~]\s*', sel.strip())[-1]
    last = re.sub(r'::?[\w-]+(\([^)]*\))?', '', last)
    if re.search(r'^[a-z]|\[|#|\*', last):
        return None
    names = re.findall(r'\.([\w-]+)', last)
    return names or None


OUR_PREFIXES = ('performance-', 'learning-', 'pa-', 'pa3-', 'shell-', 'platform-', 'council-', 'school-class-',
                'gradebook-', 'bulletin-', 'analytics-', 'filter-tags-v1', 'marquee-text-v1')


def ours(name):
    # Library classes (HeroUI: card, card__header, tabs__tab, search-field__group...) are generated by
    # components, not written in our files, so a source scan proves nothing about them.
    return name.startswith(OUR_PREFIXES) and any(name in t for t in texts.values())


# HeroUI classes whose component is never imported: nothing on screen carries them.
LIBRARY_COMPONENTS = {'breadcrumbs': 'Breadcrumbs'}


# Prefixes of class names built at run time (`performance-bar--${tone}`, 'pa-chip-' + tone).
built = set()
for t in texts.values():
    built.update(re.findall(r'([\w-]+)\$\{', t))
    built.update(re.findall(r"([\w-]+)['\"]\s*\+", t))


@functools.cache
def written(name):
    if any(name.startswith(prefix) for prefix in built):
        return True
    return any(re.search(r'(?<![\w-])' + re.escape(name) + r'(?![\w-])', t) for t in texts.values())


def matches_nothing(sel):
    """A selector naming one of our classes that no file ever writes (dead CSS) matches no element."""
    if ',' in sel:
        return False
    for name in re.findall(r'\.([\w-]+)', sel):
        if name.startswith(OUR_PREFIXES) and not written(name):
            return True
        base = name.split('__')[0]
        component = LIBRARY_COMPONENTS.get(base)
        if component and not any(re.search(r'(?<![\w-])' + component + r'(?![\w-])', t) for t in texts.values()):
            return True
    return False


accepted = []
for a, b in sorted(pairs):
    if a != b and (matches_nothing(a) or matches_nothing(b)):
        accepted.append([a, b])
        continue
    ca, cb = last_classes(a), last_classes(b)
    if not ca or not cb or a == b:
        continue
    if not all(ours(n) for n in ca + cb):
        continue
    together = [lit for lit in literals if all(re.search(r'(?<![\w-])' + re.escape(n) + r'(?![\w-])', lit) for n in ca + cb)]
    if not together:
        accepted.append([a, b])
print(len(pairs), 'conflitos;', len(accepted), 'provados separados pelo codigo')
with open(out_path, 'w', encoding='utf8') as handle:
    json.dump(measured + accepted, handle)
